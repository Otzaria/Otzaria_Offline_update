#ifndef RUNNER_SPLASH_WINDOW_H_
#define RUNNER_SPLASH_WINDOW_H_

// חלון splash נייטיב (Win32): שכבת-אלפא (layered), שקוף, click-through וללא
// מסגרת, שמציג את סמל התוכנה ממורכז על המסך הראשי עם fade-in ו-fade-out.
//
// **למה הוא קיים בכלל:** יצירת מנוע Flutter לוקחת כאן ~1.8 שניות, והיא רצה
// לפני שורת ה-Dart הראשונה — כלומר לפני שיש למי לצייר משהו. נמדד גם על
// אפליקציית `flutter create` ריקה על אותו מחשב, ולכן זה אינו משהו שקוד שלנו
// יכול לקצר. עד שהמנוע קם המשתמש ראה *כלום* אחרי הלחיצה, ופתח שוב. הסמל הזה
// עולה תוך ~30ms ונותן את המשוב המיידי במקומו.
//
// **Thread ייעודי:** החלון נוצר ומנוהל על thread נפרד עם לולאת הודעות משלו,
// כך ש-DWM מרכיב אותו והאנימציה רצה בזמן שה-thread הראשי תקוע באתחול המנוע.
// [Show] מחזיק מחסום עד שה-thread סיים את ה-fade-in, כדי שהוא לא ייתקע על
// ה-loader lock של טעינת ה-DLLs שהמנוע גורר.
//
// [Show] נקרא מ-wWinMain לפני אתחול המנוע; [Close] נקרא מ-`FlutterWindow`
// ברגע שהחלון הראשי נחשף על הפריים הראשון — ראו שם.
//
// מקור: אותו מנגנון שבאוצריא עצמה (`windows/runner/splash_window.cpp`), כדי
// ששתי התוכנות ייפתחו אותו דבר.
namespace splash {

// יוצר את ה-thread ומציג את הסמל עם fade-in (סינכרוני, בזמן המחסום). נקרא
// פעם אחת ב-wWinMain, אחרי `CoInitializeEx` (WIC דורש COM) ולפני אתחול
// המנוע. כשל (למשל פענוח ה-PNG) הוא no-op — התוכנה ממשיכה בלי splash.
void Show();

// מסמן ל-thread לבצע fade-out ולהרוס את החלון. אינו חוסם, אידמפוטנטי.
void Close();

}  // namespace splash

#endif  // RUNNER_SPLASH_WINDOW_H_
