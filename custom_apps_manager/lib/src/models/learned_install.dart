import 'app_detect_rules.dart';

/// מה שהלמידה שאחרי ההתקנה אספה.
///
/// שני השדות נפרדים **כי גורלם שונה**: [rules] נכתבים לרשומה שנוסעת על
/// הכונן, ולכן חייבים להיות בלתי-תלויים במחשב; [installDir] הוא נתיב מוחלט
/// של המחשב הזה בלבד, ונרשם ל-`locations.json` הפר-מחשבי.
///
/// ⚠️ בלי [installDir] התיקייה שהמתקין הרגע רשם הייתה נזרקת, והזיהוי היה
/// נאלץ לגזור אותה שוב מהרג'יסטרי. רישום הסרה בלי `InstallLocation` תקין
/// אינו מחזיר תיקייה כלל — ואז התוכנה מדווחת "אינה מותקנת" לנצח, אף שרגע
/// קודם ידענו בדיוק היכן היא.
class LearnedInstall {
  const LearnedInstall({this.rules, this.installDir});

  /// כללי הזיהוי שנלמדו, או `null` כשלא נלמד שום כלל חדש.
  final AppDetectRules? rules;

  /// התיקייה שהמתקין רשם ברג'יסטרי — עדות ישירה ולא ניחוש. מוחזרת גם כשלא
  /// נלמד שום כלל, כי היא שווה רישום בפני עצמה.
  final String? installDir;
}
